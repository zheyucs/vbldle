const formatDate = (value) =>
  value
    ? `${value.slice(8, 10)}/${value.slice(5, 7)}/${value.slice(2, 4)}`
    : "-";
const initials = (name) =>
  name
    .split(" ")
    .map((word) => word[0])
    .slice(0, 2)
    .join("");
const normalize = (value) => value.toLowerCase().trim();
const rarityImage = (rarity) => `assets/${rarity.toLowerCase()}-rarity.png`;
