function storageKey() {
  return `${storagePrefix}-${mode}`;
}

function currentDay() {
  return new Date().toISOString().slice(0, 10);
}

function dailySeed() {
  return currentDay()
    .split("-")
    .reduce((sum, part) => sum * 31 + Number(part), 17);
}

function formatCurrentDate() {
  const now = new Date();
  return `${String(now.getDate()).padStart(2, "0")}/${String(now.getMonth() + 1).padStart(2, "0")}/${String(now.getFullYear()).slice(-2)}`;
}

function updateModeUI() {
  const infinite = mode === "infinite";
  const modeIcon = infinite ? "./infiniteicon.png" : "./dailyicon.png";
  document.title = `vbldle (${infinite ? "infinite" : "daily"})`;
  document.body.classList.toggle("infinite-mode", infinite);
  elements.dailyMode.classList.toggle("active", !infinite);
  elements.infiniteMode.classList.toggle("active", infinite);
  elements.modeKicker.textContent = infinite ? "INFINITE MODE" : "DAILY MODE";
  elements.modeDescription.textContent = infinite
    ? "Every reset is a new style."
    : "Resetted daily.";
  elements.modeDate.textContent = infinite ? "" : formatCurrentDate();
  elements.favicon.href = modeIcon;
  elements.siteIcon.src = modeIcon;
}

function chooseTarget() {
  if (mode === "daily") {
    const seed = dailySeed();
    const styleIndex = Math.abs(seed) % styles.length;
    targetStyle = styles[styleIndex];
    const styleRoster = roster.filter((item) =>
      item.styleType.includes(targetStyle),
    );
    target =
      styleRoster[
        Math.abs(Math.floor(seed / styles.length)) % styleRoster.length
      ];
    return;
  }
  targetStyle = styles[Math.floor(Math.random() * styles.length)];
  const styleRoster = roster.filter((item) =>
    item.styleType.includes(targetStyle),
  );
  target = styleRoster[Math.floor(Math.random() * styleRoster.length)];
}

function saveGame() {
  localStorage.setItem(
    storageKey(),
    JSON.stringify({
      day: currentDay(),
      targetStyle,
      targetName: target.name,
      guesses: state.guesses.map((guess) => guess.name),
      won: state.won,
      gameOver: state.gameOver,
    }),
  );
}

function setNewGame() {
  chooseTarget();
  state.guesses = [];
  state.selected = null;
  state.won = false;
  state.gameOver = false;
  saveGame();
}

function loadGame() {
  try {
    const saved = JSON.parse(localStorage.getItem(storageKey()));
    const savedTarget = roster.find((item) => item.name === saved?.targetName);
    if (
      !savedTarget ||
      !styles.includes(saved.targetStyle) ||
      !Array.isArray(saved.guesses) ||
      (mode === "daily" && saved.day !== currentDay())
    ) {
      setNewGame();
      return;
    }
    targetStyle = saved.targetStyle;
    target = savedTarget;
    state.guesses = saved.guesses
      .map((name) => roster.find((item) => item.name === name))
      .filter(Boolean);
    state.won = saved.won === true;
    state.gameOver =
      saved.gameOver === true || state.won || state.guesses.length >= 6;
  } catch {
    setNewGame();
  }
}

function feedback(guess) {
  const styleTypeMatches = guess.styleType.filter((styleType) =>
    target.styleType.includes(styleType),
  );
  return {
    name: guess.name === target.name,
    rarity: guess.rarity === target.rarity,
    rarityDirection:
      guess.rarityOrder < target.rarityOrder
        ? "up"
        : guess.rarityOrder > target.rarityOrder
          ? "down"
          : "same",
    status: guess.status === target.status,
    release: guess.firstRelease === target.firstRelease,
    releaseDirection:
      guess.firstRelease &&
      target.firstRelease &&
      guess.firstRelease !== target.firstRelease
        ? guess.firstRelease < target.firstRelease
          ? "later"
          : "earlier"
        : "same",
    styleType:
      styleTypeMatches.length === target.styleType.length &&
      styleTypeMatches.length === guess.styleType.length
        ? "exact"
        : styleTypeMatches.length
          ? "partial"
          : "none",
  };
}

function renderSuggestions(query = "") {
  const search = normalize(query);
  const matches = roster.filter(
    (item) =>
      (normalize(item.name).includes(search) ||
        item.styleType.some((styleType) =>
          normalize(styleType).includes(search),
        )) &&
      !state.guesses.some((guess) => guess.name === item.name),
  );
  elements.suggestions.innerHTML = matches
    .map(
      (item) =>
        `<button type="button" class="suggestion" data-name="${item.name}">${styleImage(item.name) ? `<img src="${styleImage(item.name)}" alt="">` : ""}<strong>${item.name}</strong></button>`,
    )
    .join("");
  elements.suggestions.classList.toggle(
    "visible",
    matches.length > 0 && document.activeElement === elements.input,
  );
}

function cell(content, tone, extra = "") {
  return `<td class="result-cell ${tone} ${extra}">${content}</td>`;
}

function renderGuess(guess, guessNumber) {
  const result = feedback(guess);
  const releaseValue = formatDate(guess.firstRelease);
  const releaseDirection =
    result.releaseDirection === "same"
      ? ""
      : `<small class="release-direction"><img src="assets/unknown.png" alt="Unknown date comparison" /> style was released ${result.releaseDirection}</small>`;
  const styleTypeValue = guess.styleType
    .map((styleType) => `<span>${styleType}</span>`)
    .join("");
  return `<tr class="guess-row">
    <td class="guess-number">${guessNumber}</td>
    ${cell(`${styleImage(guess.name) ? `<img class="style-icon" src="${styleImage(guess.name)}" alt="">` : ""}<strong>${guess.name}</strong>`, result.name ? "correct" : "wrong", "name-cell")}
    ${cell(`<span class="rarity-value"><img src="${rarityImage(guess.rarity)}" alt="${guess.rarity}"><span>${guess.rarity}</span>${result.rarityDirection !== "same" ? `<span class="arrow">${result.rarityDirection === "up" ? "↑" : "↓"}</span>` : ""}</span>`, result.rarity ? "correct" : "wrong")}
    ${cell(guess.status, result.status ? "correct" : "wrong")}
    ${cell(`<span class="release-value">${releaseValue}${releaseDirection}</span>`, result.release ? "correct" : "wrong")}
    ${cell(styleTypeValue, result.styleType === "exact" ? "correct" : result.styleType === "partial" ? "partial" : "wrong", "styles-cell")}
  </tr>`;
}

function renderBoard(animateLatest = false) {
  elements.board.querySelectorAll(".guess-row").forEach((row) => row.remove());
  state.guesses.slice().forEach((guess, index) => {
    const row = renderGuess(guess, index + 1).replace(
      '<tr class="guess-row">',
      `<tr class="guess-row${animateLatest && index === state.guesses.length - 1 ? " latest-guess" : ""}">`,
    );
    elements.board.insertAdjacentHTML("beforeend", row);
  });
  elements.count.textContent = `${state.guesses.length} / 6`;
  elements.reset.hidden = mode === "daily" || !state.gameOver;
}

function renderStatus() {
  if (state.won) {
    elements.status.innerHTML = `<span class="status-dot win"></span> You guessed the style in ${state.guesses.length} ${state.guesses.length === 1 ? "guess" : "guesses"}!`;
  } else if (state.gameOver) {
    elements.status.innerHTML = `<span class="status-dot"></span> The style was <strong>${target.name}</strong>!`;
  } else if (state.guesses.length) {
    elements.status.innerHTML = `<span class="status-dot"></span> Keep looking. ${6 - state.guesses.length} guesses remaining.`;
  } else {
    elements.status.textContent = "Choose a style to begin.";
  }
}

function showRoundReport() {
  const attempts = Math.min(state.guesses.length, resultIcons.length);
  elements.reportTitle.textContent = state.won ? "You got it!" : "Round over";
  elements.reportIcon.hidden = !state.won;
  if (state.won)
    elements.reportIcon.src = `assets/${resultIcons[attempts - 1]}`;
  elements.reportCopy.textContent = state.won
    ? `${target.name} guessed in ${attempts} ${attempts === 1 ? "guess" : "guesses"}.`
    : `The style was ${target.name}.`;
  elements.report.showModal();
  renderStatus();
}

function revealFinished() {
  window.clearTimeout(reportTimer);
  reportTimer = window.setTimeout(showRoundReport, 5 * 180 + 760);
}

function submitGuess(name) {
  const guess = roster.find((item) => item.name === name);
  if (
    !guess ||
    state.guesses.some((item) => item.name === name) ||
    state.gameOver
  )
    return;
  state.guesses.push(guess);
  state.selected = null;
  elements.input.value = "";
  elements.suggestions.classList.remove("visible");
  if (guess.name === target.name) {
    state.won = true;
    state.gameOver = true;
  } else if (state.guesses.length >= 6) {
    state.gameOver = true;
  }
  renderBoard(true);
  saveGame();
  if (state.gameOver) revealFinished();
}

elements.input.addEventListener("input", (event) =>
  renderSuggestions(event.target.value),
);
elements.input.addEventListener("focus", () =>
  renderSuggestions(elements.input.value),
);
elements.input.addEventListener("keydown", (event) => {
  if (event.key === "Enter") {
    event.preventDefault();
    const first = elements.suggestions.querySelector(".suggestion");
    submitGuess(state.selected || first?.dataset.name);
  }
  if (event.key === "Escape") elements.suggestions.classList.remove("visible");
});
elements.suggestions.addEventListener("click", (event) => {
  const option = event.target.closest(".suggestion");
  if (!option) return;
  state.selected = option.dataset.name;
  elements.input.value = option.dataset.name;
  elements.suggestions.classList.remove("visible");
  elements.form.requestSubmit();
});
elements.form.addEventListener("submit", (event) => {
  event.preventDefault();
  submitGuess(state.selected || elements.input.value);
});
elements.reset.addEventListener("click", () => {
  if (mode === "daily") return;
  window.clearTimeout(reportTimer);
  if (elements.report.open) elements.report.close();
  setNewGame();
  elements.input.value = "";
  elements.suggestions.classList.remove("visible");
  elements.status.classList.remove("celebrate");
  renderBoard();
  renderStatus();
  elements.input.focus();
});
elements.closeReport.addEventListener("click", () => elements.report.close());
function switchMode(nextMode) {
  if (mode === nextMode) return;
  window.clearTimeout(reportTimer);
  if (elements.report.open) elements.report.close();
  mode = nextMode;
  history.replaceState(null, "", `#${mode}`);
  loadGame();
  updateModeUI();
  elements.input.value = "";
  elements.suggestions.classList.remove("visible");
  renderBoard();
  renderStatus();
  renderSuggestions();
}
elements.dailyMode.addEventListener("click", () => switchMode("daily"));
elements.infiniteMode.addEventListener("click", () => switchMode("infinite"));
document.addEventListener("click", (event) => {
  if (
    !event.target.closest("#guess-form") &&
    !event.target.closest("#suggestions")
  )
    elements.suggestions.classList.remove("visible");
});
loadGame();
updateModeUI();
renderBoard();
renderStatus();
if (state.gameOver) revealFinished();
renderSuggestions();
